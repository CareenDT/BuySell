def normalize_lang(lang: str | None) -> str:
    if not lang:
        return "ru"
    low = lang.lower().strip()
    if low in TRANSLATIONS:
        return low
    if len(low) >= 2 and low[:2] in TRANSLATIONS:
        return low[:2]
    return "ru"


def translate(lang: str, key: str) -> str:
    loc = normalize_lang(lang)
    return TRANSLATIONS.get(loc, TRANSLATIONS["ru"]).get(
        key, TRANSLATIONS["en"].get(key, key)
    )
